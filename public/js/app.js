function scoreGuess(g,a){
  const res=Array(5).fill('x'), cnt={};
  for(const c of a) cnt[c]=(cnt[c]||0)+1;
  for(let i=0;i<5;i++){ if(g[i]===a[i]){res[i]='g';cnt[g[i]]--;} }
  for(let i=0;i<5;i++){ if(res[i]==='g')continue; if(cnt[g[i]]>0){res[i]='y';cnt[g[i]]--;} }
  return res;
}
