// pick white or dark text for a given accent so it's always readable
function readableOn(hex){
  const c = hex.replace('#',''); if(c.length<6) return '#fff';
  const r=parseInt(c.substr(0,2),16)/255,g=parseInt(c.substr(2,2),16)/255,b=parseInt(c.substr(4,2),16)/255;
  const lin=x=> x<=0.03928 ? x/12.92 : Math.pow((x+0.055)/1.055,2.4);
  const L=0.2126*lin(r)+0.7152*lin(g)+0.0722*lin(b);
  return L>0.55 ? '#1b1410' : '#ffffff';
}

