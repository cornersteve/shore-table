  TOT    = t.data.map(r=>({ id:r.id, a:r.option_a, b:r.option_b, count_a:r.count_a, count_b:r.count_b, vid:r.venue_id||null }));
  HS     = hsq.data.map(r=>({ id:r.id, q:r.prompt, opts:[r.option_a,r.option_b,r.option_c,r.option_d], vid:r.venue_id||null }));
