/* Runs once at boot, after the venue is resolved. Shared rows (no vid) stay
   for everyone; a venue's custom rows stay only at that venue AND only while
   its paid custom_questions flag is on, so a lapsed venue's rows go dormant
   without deleting anything and no venue ever sees another venue's rows. */
/* One full round per game, as dealt above. 28_custom_only_retire.sql keeps
   the SAME numbers in content_floor(); change them together. */
const MIN_CUSTOM_ONLY = { guess_the_split:5, who_knows_who:12, trivia:8, wordy:5, who_invited_you:5, fortune_teller:3, all_talk:5 };
function filterContentForVenue(){
  const v = venue();
  const keep = it => !it.vid || (it.vid === state.venue && !!(v && v.customQuestions));
  TOT = TOT.filter(keep); HS = HS.filter(keep); TRIVIA = TRIVIA.filter(keep);
  WORDS = WORDS.filter(keep); WIY = WIY.filter(keep); FORTUNES = FORTUNES.filter(keep);
  ATCATS = ATCATS.filter(keep);
  // Custom-only, per game (paid tier): deal ONLY this venue's rows where it
  // asked for that AND its pool clears one full round. Below the floor it
  // FAILS OPEN to the normal custom-first blend, so a thin pool can never
  // shorten or break a game at the table.
  if(v && v.customQuestions && Array.isArray(v.customOnly) && v.customOnly.length){
    const only = (list, g) => {
      if(!v.customOnly.includes(g)) return list;
      const own = list.filter(it => it.vid);
      return own.length >= MIN_CUSTOM_ONLY[g] ? own : list;
    };
    TOT = only(TOT, 'guess_the_split'); HS = only(HS, 'who_knows_who'); TRIVIA = only(TRIVIA, 'trivia');
    WORDS = only(WORDS, 'wordy'); WIY = only(WIY, 'who_invited_you');
    FORTUNES = only(FORTUNES, 'fortune_teller'); ATCATS = only(ATCATS, 'all_talk');
  }
}

