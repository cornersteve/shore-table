/* Payouts. Solo: a winning $1 ticket returns $6 (5 to 1 plus the stake).
   Multiplayer: the whole pot, split across the winning tickets. A pot
   nobody claimed just disappears, no rollover, same as the live show. */
function hrSettle(w){
  const pot = hrPot();
  const winT = hr.bets.reduce((s,b)=>s+b[w-1],0);
  hr.results = hr.players.map((p,i)=>{
    const spent = hr.bets[i].reduce((x,y)=>x+y,0);
    const won = hr.mode==='solo'
      ? hr.bets[i][w-1]*6
      : (winT ? Math.round(pot*hr.bets[i][w-1]/winT*100)/100 : 0);
    return { spent, won };
  });
  hr.results.forEach((r,i)=>{
    const p = hr.players[i];
    p.bal = Math.round((p.bal + r.won)*100)/100;
    if(p.bal < 1) p.out = true;   // cannot buy a ticket = out
  });
  hr.winHorse = w; hr.potWas = pot; hr.winTicketsWas = winT;
}

