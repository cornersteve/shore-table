reg('hr_race', (el)=>{
  // full bleed, same rule as cornhole and shore pour
  el.style.padding = '0';
  el.innerHTML = `
    <div class="ch-stage" id="hrStage">
      <canvas id="hrCv"></canvas>
      <div class="ch-bar ch-bar--solid" id="hrBar"></div>
      <div class="hr-cage" id="hrCage">
        <svg width="90" height="96" viewBox="0 0 100 106" aria-hidden="true">
          <g class="wires" stroke="#cfc9bf" stroke-width="2.5" fill="none">
            <circle cx="50" cy="46" r="34"/>
            <ellipse cx="50" cy="46" rx="15" ry="34"/>
            <ellipse cx="50" cy="46" rx="26" ry="34"/>
          </g>
          <line x1="8" y1="46" x2="92" y2="46" stroke="#8d867b" stroke-width="3"/>
          <path d="M50,80 L32,104 M50,80 L68,104" stroke="#8d867b" stroke-width="4" fill="none"/>
        </svg>
        <div class="hr-dice" id="hrDice"></div>
      </div>
      <div class="hr-call" id="hrCall"></div>
    </div>`;
  const q = s => el.querySelector(s);
  const cv = q('#hrCv'), ctx = cv.getContext('2d');
  const callEl = q('#hrCall'), cageEl = q('#hrCage'), diceEl = q('#hrDice');
  const FONT = getComputedStyle(document.body).getPropertyValue('--font-d');

  /* fixed design space, cornhole pattern */
  const DW = 390, DH = 760, DPR = Math.min(2, window.devicePixelRatio || 1);
  let W = 0, H = 0, SCL = 1, OX = 0, OY = 0;
  function size(){
    const st = q('#hrStage');
    W = st.clientWidth; H = st.clientHeight;
    cv.width = Math.round(W*DPR); cv.height = Math.round(H*DPR);
    ctx.setTransform(DPR, 0, 0, DPR, 0, 0);
    SCL = Math.min(W / DW, H / DH);
    OX = (W - DW * SCL) / 2; OY = (H - DH * SCL) / 2;
  }

  /* board geometry: curtain valance, finish zone, checkered line, then the
     grid mat. Rows are counted from the bottom; a horse at position p sits
     in row p and crossing (p >= len) puts it past the checker. */
  const MATX = 12, MATW = 366, LANEW = MATW/6;
  const CURT = 70, CHKTOP = 128, CHK = 14, TRKTOP = CHKTOP + CHK, TRKBOT = 748;
  const R = hr.race;
  const cellH = ()=> (TRKBOT - TRKTOP) / R.len;
  const laneCx = n => MATX + LANEW*(n-1) + LANEW/2;

  /* per-horse display state: p is the drawn position, hops ease it along */
  let ay = {};
  const resetAnim = ()=>{ ay = {}; R.lanes.forEach(n=>{ ay[n] = { p:R.pos[n-1], from:0, to:0, t0:0, dur:0 }; }); };
  resetAnim();
  let winN = 0, winAt = 0;

  /* async race director; the token + isConnected guard kills stale loops */
  const run = hr.run = {};
  const ok = ()=> hr.run === run && cv.isConnected;
  const wait = ms => new Promise(r => setTimeout(r, ms));

  function bar(dice){
    const info = hr.mode==='solo' ? 'Bank ' + hrFmt(hr.players[0].bal) : 'Pot ' + hrFmt(hrPot());
    q('#hrBar').innerHTML = `<span class="rd">${R.sudden ? 'Sudden death' : 'Race ' + hr.raceN}</span>
      <span class="sc" style="font-size:14px;color:#cfc9bf">${info}</span>
      ${dice ? `<span class="rt" style="display:flex;justify-content:center;gap:6px;align-items:center">${dice.map(d=>hrChip(d,true)).join('')}</span>` : ''}`;
  }

  /* the announcer: lines build one at a time, holding for his pauses.
     A phase's `dice` list flips that many face-down cage dice face-up AS
     the line prints, so the call and the reveal land together. */
  async function say(phases){
    callEl.innerHTML = ''; callEl.classList.add('show');
    for(const ph of phases){
      if(!ok()) return;
      if(ph.dice) ph.dice.forEach(n=> revealDie(n));
      const d = document.createElement('div');
      d.className = 'ln' + (ph.big ? ' big' : '');
      d.textContent = ph.t;
      callEl.appendChild(d);
      await wait(ph.hold);
    }
    callEl.classList.remove('show');
  }
  /* the cage: spins with the dice tumbling, then settles FACE-DOWN and
     STAYS UP while the announcer calls it (like the live show, the
     cage sits there, but the dice only turn over as he reads them, so the
     call keeps its suspense). The race loop hides it when horses move. */
  async function rollCage(fast){
    cageEl.classList.add('show','rolling');
    const spin = setInterval(()=>{
      diceEl.innerHTML = [0,1,2].map(()=> hrChip(R.lanes[Math.floor(Math.random()*R.lanes.length)])).join('');
    }, 90);
    diceEl.innerHTML = [0,1,2].map(()=> hrChip(R.lanes[Math.floor(Math.random()*R.lanes.length)])).join('');
    await wait(fast ? 550 : 800);
    clearInterval(spin);
    cageEl.classList.remove('rolling');
    diceEl.innerHTML = [0,1,2].map(()=> hrChipDown()).join('');
  }
  function revealDie(n){
    const d = diceEl.querySelector('.hr-die.down');
    if(d) d.outerHTML = hrChip(n);
  }
  function hideCage(){ cageEl.classList.remove('show','rolling'); }
  /* one hop, one horse, one space */
  function hop(n, fast){
    return new Promise(res=>{
      const a = ay[n], dur = fast ? 240 : 300;
      R.pos[n-1]++;
      a.from = a.p; a.to = Math.min(R.pos[n-1], R.len + 0.9);
      a.t0 = performance.now(); a.dur = dur;
      setTimeout(()=>{ a.p = a.to; res(); }, dur + (fast ? 90 : 130));
    });
  }

  // hr.rig: test hook (pp.state pattern) — an array of [d,d,d] rolls consumed
  // before random ones. Console-only; everything here is client-side anyway.
  const draw3 = ()=>{
    if(Array.isArray(hr.rig) && hr.rig.length) return hr.rig.shift().slice().sort((a,b)=>a-b);
    return [0,0,0].map(()=> R.lanes[Math.floor(Math.random()*R.lanes.length)]).sort((a,b)=>a-b);
  };
  function classify(dice){
    const c = {}; dice.forEach(d=> c[d] = (c[d]||0)+1);
    const ns = Object.keys(c).map(Number).sort((a,b)=>a-b);
    if(ns.length === 1) return { kind:'triple', n:ns[0] };
    if(ns.length === 2){ return { kind:'double', d:ns.find(x=>c[x]===2), s:ns.find(x=>c[x]===1) }; }
    return { kind:'singles', ns };
  }

  async function suddenDeath(tied){
    await say([
      { t:`We have ${tied.length} horses across the finish line.`, hold:950 },
      { t:'You know what that means?', hold:900 },
      { t:'SUDDEN DEATH!!', big:true, hold:1250 }
    ]); if(!ok()) return;
    R.sudden++;
    R.len = HR_SUDDEN_LEN;
    R.lanes = tied.slice();
    tied.forEach(n=>{ R.pos[n-1] = 0; });
    resetAnim();
    bar();
    await wait(500); if(!ok()) return;
    await say([{ t:'WHO DO YOU WAAANT?', big:true, hold:1200 }]);
  }

  async function race(){
    await wait(450); if(!ok()) return;
    await say([{ t:'Betting is closed.', hold:1000 }]); if(!ok()) return;
    await say([{ t:'WHO DO YOU WAAANT?', big:true, hold:1450 }]); if(!ok()) return;
    let rolls = 0;
    while(ok()){
      rolls++;
      const fast = rolls > 9;
      const dice = draw3();
      const cls = classify(dice);
      const gain = {}; dice.forEach(d=> gain[d] = (gain[d]||0)+1);
      const crossers = R.lanes.filter(n => R.pos[n-1] + (gain[n]||0) >= R.len);
      const contenders = R.lanes.filter(n => R.pos[n-1] >= R.len - 3).length;
      /* the tease is only for a roll that DOES win it, while 2+ horses were
         in striking range; ties read normally, triples carry their own drama */
      const cage = crossers.length === 1 && contenders >= 2 && cls.kind !== 'triple';
      await rollCage(fast); if(!ok()) return;
      /* a matched SIX gets the announcer's "on the outside" tag (the white
         horse runs lane six); winner-tease singles read plain */
      const six = n => n === 6 ? HR_YELL[5] + ' on the outside' : HR_YELL[n-1];
      /* each phase's `dice` flips those cage dice face-up with the line, so
         the numbers stay hidden until the exact moment they are called */
      let phases = [], order = [];
      if(cls.kind === 'triple'){
        /* triples hold longest: extra beat before the number, extra after */
        phases = [
          { t:'We have a TRIPLE number.', hold:1000 },
          { t:'WHO DO YOU WAAANT?', big:true, hold:1250 },
          { t:`It's a TRIPLE ${six(cls.n)}!`, big:true, hold:1500, dice:[cls.n, cls.n, cls.n] }
        ];
        order = [cls.n, cls.n, cls.n];
      } else if(cls.kind === 'double'){
        if(cage && crossers[0] === cls.s){
          /* the single is the winner: read the double first, winner last */
          phases = [
            { t:`A DOUBLE ${HR_WORDS[cls.d-1]} and a number...`, hold:1150, dice:[cls.d, cls.d] },
            { t:`${HR_YELL[cls.s-1]}!`, big:true, hold:1250, dice:[cls.s] }
          ];
          order = [cls.d, cls.d, cls.s];
        } else {
          phases = [
            { t:`Number ${HR_WORDS[cls.s-1]} and a DOUBLE...`, hold:1150, dice:[cls.s] },
            { t:`${six(cls.d)}!`, big:true, hold:1300, dice:[cls.d, cls.d] }
          ];
          if(cls.d === 5 && !crossers.length) phases.push({ t:'NUMBER FIVE IS ALIVE!', big:true, hold:1050 });
          order = [cls.s, cls.d, cls.d];
        }
      } else if(cage){
        const w = crossers[0], others = cls.ns.filter(n=>n!==w);
        phases = [
          { t:`Number ${HR_WORDS[others[0]-1]}, ${HR_WORDS[others[1]-1]} and...`, hold:750, dice: others.slice() },
          { t:`${HR_YELL[w-1]}!`, big:true, hold:1100, dice:[w] }
        ];
        order = [...others, w];
      } else {
        phases = [{ t:`Number ${HR_WORDS[cls.ns[0]-1]}, ${HR_WORDS[cls.ns[1]-1]} and ${HR_WORDS[cls.ns[2]-1]}`, hold: fast ? 750 : 950, dice: cls.ns.slice() }];
        order = cls.ns.slice();
      }
      if(cage) phases = [
        { t:'I have a winner in the cage.', hold:1100 },
        { t:'WHO DO YOU WAAANT?', big:true, hold:1300 },
        ...phases
      ];
      await say(phases); if(!ok()) return;
      hideCage();   // the cage and its roll leave with the announcer text
      bar(dice);
      for(const n of order){ await hop(n, fast); if(!ok()) return; }
      const done = R.lanes.filter(n => R.pos[n-1] >= R.len);
      if(done.length === 1){
        winN = done[0]; winAt = performance.now();
        const rct = cv.getBoundingClientRect();
        confettiBurst(rct.left + OX + laneCx(winN)*SCL, rct.top + OY + (TRKTOP - 30)*SCL);
        /* the winner call spells the number normally (the operator): the stretched
           yell is for roll reveals, not the result */
        await say([{ t:`NUMBER ${HR_WORDS[winN-1].toUpperCase()} WINS!`, big:true, hold:1800 }]);
        if(!ok()) return;
        hrSettle(winN);
        go('hr_result',{exit:true});
        return;
      }
      if(done.length > 1){ await suddenDeath(done); if(!ok()) return; continue; }
      await wait(fast ? 260 : 380);
    }
  }

  /* ---- drawing ---- */
  const horsePath = new Path2D(HR_PATH);
  function line(x1,y1,x2,y2){ ctx.beginPath(); ctx.moveTo(x1,y1); ctx.lineTo(x2,y2); ctx.stroke(); }
  function rr(x,y,w,hh,r){ ctx.beginPath(); ctx.moveTo(x+r,y); ctx.arcTo(x+w,y,x+w,y+hh,r); ctx.arcTo(x+w,y+hh,x,y+hh,r); ctx.arcTo(x,y+hh,x,y,r); ctx.arcTo(x,y,x+w,y,r); ctx.closePath(); }
  function drawHorse(n, cx, yBot, rock, s){
    const c = HR_HORSES[n-1];
    ctx.save();
    ctx.translate(cx, yBot); ctx.rotate(rock);
    ctx.scale(s, s); ctx.translate(-50, -134);
    ctx.fillStyle = c.f; ctx.fill(horsePath);
    ctx.strokeStyle = c.o; ctx.lineWidth = 2.5; ctx.stroke(horsePath);
    ctx.strokeStyle = c.t; ctx.lineWidth = 3.5; ctx.lineCap = 'round';
    ctx.beginPath(); ctx.moveTo(34,42); ctx.lineTo(9,50); ctx.moveTo(34,42); ctx.lineTo(64,84); ctx.moveTo(64,84); ctx.lineTo(60,110); ctx.stroke();
    ctx.fillStyle = c.t;
    ctx.beginPath(); ctx.arc(34,42,4.5,0,Math.PI*2); ctx.fill();
    ctx.beginPath(); ctx.arc(64,84,4.5,0,Math.PI*2); ctx.fill();
    ctx.fillStyle = n===1 ? '#cfc9c0' : '#241f1a';
    ctx.beginPath(); ctx.arc(45,26,3,0,Math.PI*2); ctx.fill();
    ctx.fillStyle = '#fff'; rr(38,113,24,20,5); ctx.fill();
    ctx.strokeStyle = 'rgba(0,0,0,.25)'; ctx.lineWidth = 1.5; ctx.stroke();
    ctx.fillStyle = c.d; ctx.font = '800 17px ' + FONT; ctx.textAlign = 'center';
    ctx.fillText(n, 50, 129);
    ctx.restore();
  }
  function eased(a, now){
    if(!a.dur || now >= a.t0 + a.dur){ a.p = a.to || a.p; return a.p; }
    const u = (now - a.t0)/a.dur, e = 1 - Math.pow(1-u, 3);
    return a.from + (a.to - a.from)*e;
  }
  function draw(now){
    ctx.fillStyle = '#14110e'; ctx.fillRect(0, 0, W, H);
    ctx.save(); ctx.translate(OX, OY); ctx.scale(SCL, SCL);
    const exL = -OX/SCL, exW = DW + 2*OX/SCL;
    // curtain valance
    ctx.fillStyle = '#6b1622'; ctx.fillRect(exL, -OY/SCL, exW, CURT + OY/SCL);
    ctx.fillStyle = 'rgba(0,0,0,.24)';
    for(let x = exL; x < exL + exW; x += 26) ctx.fillRect(x, -OY/SCL, 10, CURT + OY/SCL);
    ctx.fillStyle = '#c9a13f'; ctx.fillRect(exL, CURT - 3, exW, 3);
    // the mat
    ctx.fillStyle = '#1c1916'; ctx.fillRect(MATX, CURT + 8, MATW, TRKBOT - CURT);
    ctx.strokeStyle = 'rgba(255,255,255,.3)'; ctx.lineWidth = 2;
    ctx.strokeRect(MATX, CURT + 8, MATW, TRKBOT - CURT);
    // finish zone label
    ctx.fillStyle = 'rgba(255,255,255,.18)';
    ctx.font = '700 12px ' + FONT; ctx.textAlign = 'center';
    ctx.fillText('F I N I S H', DW/2, CHKTOP - 12);
    // checkered line
    const sq = CHK/2;
    for(let i = 0; i < 2; i++) for(let x = MATX; x < MATX + MATW; x += sq){
      ctx.fillStyle = ((x - MATX)/sq + i) % 2 < 1 ? '#efeae0' : '#211d19';
      ctx.fillRect(x, CHKTOP + i*sq, Math.min(sq, MATX + MATW - x), sq);
    }
    // grid
    const ch = cellH();
    ctx.strokeStyle = 'rgba(255,255,255,.13)'; ctx.lineWidth = 1;
    for(let rI = 1; rI < R.len; rI++){ const y = TRKBOT - rI*ch; line(MATX, y, MATX + MATW, y); }
    for(let l = 1; l < 6; l++){ const x = MATX + LANEW*l; line(x, TRKTOP, x, TRKBOT); }
    // start line, a touch bolder
    ctx.strokeStyle = 'rgba(255,255,255,.28)'; ctx.lineWidth = 2;
    line(MATX, TRKBOT, MATX + MATW, TRKBOT);
    // horses, furthest first so nearer ones overlap naturally
    const list = R.lanes.map(n=>({ n, p: eased(ay[n], now) })).sort((a,b)=> b.p - a.p);
    const s = ch > 70 ? 0.56 : 0.5;
    for(const it of list){
      const a = ay[it.n];
      const moving = now < a.t0 + a.dur;
      const u = moving ? (now - a.t0)/a.dur : 0;
      const rock = moving ? Math.sin(u*Math.PI) * -0.12 : 0;
      const lift = moving ? Math.sin(u*Math.PI) * 6 : 0;
      const bounce = winN === it.n ? Math.abs(Math.sin((now - winAt)/180)) * 8 : 0;
      drawHorse(it.n, laneCx(it.n), TRKBOT - Math.min(it.p, R.len + 0.9)*ch - 3 - lift - bounce, rock, s);
    }
    ctx.restore();
  }
  function tick(now){
    if(!cv.isConnected){ ro.disconnect(); return; }
    draw(now);
    requestAnimationFrame(tick);
  }
  hr.drawNow = ()=> draw(performance.now());   // read-only debug handle for tests, pp.state pattern
  const ro = new ResizeObserver(size);
  ro.observe(q('#hrStage'));
  size();
  bar();
  requestAnimationFrame(tick);
  race();
});

