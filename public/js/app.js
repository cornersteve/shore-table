// Shared reveal: just the two percentages, counting up from 50 to the real
// split. There is deliberately NO proportional bar here. The guess slider is a
// pointer (drag it toward the side you think wins), while a stacked bar is an
// area (the seam marks A's share), so the same divider would move the opposite
// way for the same answer. The numbers are the score anyway: the miss is
// |your call - real|, and .bar-num.win still colors the winning side.
function totNumsHtml(item, aPct, bPct, side){
  return `
    <div class="bar-nums">
      <div><div class="bar-num ${side==='a'?'win':'lose'}" data-t="${aPct}">50%</div><div class="bar-lab">${item.a}</div></div>
      <div><div class="bar-num ${side==='b'?'win':'lose'}" data-t="${bPct}">50%</div><div class="bar-lab r">${item.b}</div></div>
    </div>`;
}
function totAnimateNums(el){
  el.querySelectorAll('.bar-num').forEach(n=>{
    const target=+n.dataset.t, t0=performance.now(), dur=1050, from=50;
    (function tick(now){const p=Math.min(1,(now-t0)/dur);const e=1-Math.pow(1-p,3);n.textContent=Math.round(from+(target-from)*e)+'%';if(p<1)requestAnimationFrame(tick);})(t0);
  });
}
function totMissLine(miss){
  if(miss===0)  return 'Perfect call.';
  if(miss<=2)   return 'Dead on.';
  if(miss<=5)   return 'Nailed it.';
  if(miss<=12)  return 'Close call.';
  if(miss<=25)  return 'The crowd drifted on you.';
  return 'Way off.';
}

