// Per-device "fresh questions first" memory. Each game keeps an ordered list
// of question ids this phone has already been SHOWN (oldest first). New decks
// deal unseen questions before recycling the least-recently-seen, so repeats
// only start once the whole pool has been played on this device. Keyed on the
// permanent question ids, and fails OPEN: if localStorage is blocked, decks
// are simply fully random like before.
function seenList(key){ try { const r=lsGet(key); return r?JSON.parse(r):[]; } catch(e){ return []; } }
function markSeen(key,id){ try { const a=seenList(key).filter(x=>x!==id); a.push(id); lsSet(key, JSON.stringify(a.slice(-400))); } catch(e){} }
function freshDeck(list, key, count){
  const rank = new Map(seenList(key).map((id,i)=>[id,i]));
  const idx = shuffle(list.map((_,i)=>i));
  // Custom-first: by the time decks are built, any item still carrying a vid
  // is THIS venue's paid custom content (filterContentForVenue dropped the
  // rest), so unseen custom rows (-2) deal before unseen shared ones (-1).
  // The venue's questions lead for every device that hasn't met them yet,
  // then everything recycles together, oldest-seen first.
  // stable sort: unseen (rank -1) keep their shuffled order and come first,
  // seen questions follow oldest-seen first
  const r = i => rank.has(list[i].id) ? rank.get(list[i].id) : (list[i].vid ? -2 : -1);
  idx.sort((a,b)=> r(a) - r(b));
  return count ? idx.slice(0,count) : idx;
}
