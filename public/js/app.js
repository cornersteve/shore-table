/* ---------- GUESS THE SPLIT (internal id: guess_the_split) ----------
   Diner-facing rename + new flow. All internals unchanged on purpose:
   gts_questions, cast_gts_vote, st_seen_gts, the guess_the_split play counter.
   Flow: pick your side (this is the real vote, the community pool keeps
   growing), then call what percent of players picked it too, then the reveal
   scores you on how close your call was. Solo = 5 rounds, average miss.
   Group = 2 to 8 players take turns on the same question, lowest total miss
   after 5 rounds wins. */

// Count the vote only the first time this device answers this question. The
// server function itself only records for an ACTIVE venue, so a lead's demo
// tap still shows the split but changes no counter.
async function castTotVoteOnce(item, side){
  let ca = item.count_a, cb = item.count_b;
  if(!totVoted(item.id)){
    try {
      // six seconds, then the split we loaded stands in (the reveal never hangs)
      const { data, error } = await Promise.race([
        db.rpc('cast_gts_vote', { p_question_id:item.id, p_side:side, p_venue_id:state.venue }),
        new Promise(r=> setTimeout(()=> r({ data:null, error:'timeout' }), 6000)) ]);
      if(!error && data && data.length){ ca=data[0].count_a; cb=data[0].count_b; item.count_a=ca; item.count_b=cb; }
    } catch(e){ /* offline: fall back to the counts we loaded */ }
    totMarkVoted(item.id);
  }
  return [ca, cb];
}

